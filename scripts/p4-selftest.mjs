import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const content = JSON.parse(readFileSync('content.json', 'utf8'));
const html = readFileSync('index.html', 'utf8');
// V3 hero: the terrain mount is retired. The hero's log strip must still be the newest real entry.
assert(!html.includes('data-island="terrain"'), 'V3 hero has no terrain mount');
const newest = [...content.journey].sort((a, b) => b.date.localeCompare(a.date))[0];
const strip = html.match(/class="v3-latest" data-newest="([^"]+)" data-day="(\d+)"/);
assert(strip, 'Hero log strip exists');
assert.equal(strip[1], newest.date);
assert.equal(Number(strip[2]), newest.day);
assert(html.includes(`href="journey.html#day-${newest.day}"`), 'Hero links to the newest entry');
assert(html.includes('<span class="sr">Go deep. Build it.</span>'), 'Flip-board headline has readable text before JS');
assert(html.includes('href="https://toolkit.deependhq.com/sign-in"'), 'Dock carries Login');
assert(!/theme-switch|only-navy|only-classic|data-dh-scheme|dh_theme|dh_scheme/.test(html), 'No theme switch or storage');
const byDate = new Map(content.journey.map(e => [e.date,e]));
const clocks = ['15:00','16:30','18:00','19:00','23:00','01:03','02:00'];
assert.deepEqual(content.lanes.map(s=>s.clock),clocks);
assert.deepEqual([...html.matchAll(/class="wx-stage" data-hour="([^"]+)"/g)].map(m=>m[1]),clocks);
assert.equal((html.match(/Illustrative command, not live output/g)||[]).length,7);
assert(!html.includes('last outreach lane:'));
assert(html.includes('I lead B2B growth. Then I build the systems behind it.'));
assert(html.includes('href="#stack"'));
assert(!html.includes('deploy ok'));
const journey = readFileSync('JourneyPage.jsx','utf8');
assert(journey.includes('id={`day-${entry.day}`}'));
assert(journey.includes("const m = /^#day-(\\d+)$/.exec(location.hash || '');"), 'Journey expands deep-linked entries beyond the first static batch');
console.log(`P4/V3: hero strip day ${newest.day}, ${byDate.size} real entries, seven exact clocks, existing journey anchors and honest snippets verified.`);
