#!/usr/bin/env node
// generate-loading-figure.mjs : original pixel figure frames for the
// LoadingAnimation hero. Replaces the component's built-in frames, which
// were sampled from a third-party video of a real person and must not be
// published. This figure is procedural: a bald head, a beard mass and a
// blazer torso, drawn with the deependhq scouter-bust proportions, that
// narrows and shifts as it "turns". No likeness, no copyright.
//
//   node scripts/generate-loading-figure.mjs   (writes ../components/client/r6/loading-figure.ts)
//
// No em dashes in output.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const GW = 66;
const GH = 53;
const N = 36; // frames per full turn, 10 degrees each

// Figure geometry in grid cells. All coordinates are row-major (x, y).
const CX = 33; // figure centre column
const HEAD_CY = 20; // head centre row
const HEAD_R = 8.6; // head radius (vertical)
const EYE_Y = 17;

function fig(x, y, th) {
  const cos = Math.cos(th);
  const abs = Math.abs(cos);
  const w = Math.max(0.28, abs); // width factor: 1 front, ~0.28 profile
  // head: vertical ellipse, width collapses as the figure turns
  const hx = (x - CX) / (HEAD_R * w);
  const hy = (y - HEAD_CY) / HEAD_R;
  if (hx * hx + hy * hy <= 1) {
    // two eye pixels visible from the front only
    if (EYE_Y === y && abs > 0.82 && (x === CX - 2 || x === CX + 2)) return false;
    return true;
  }
  // beard mass under the head, mirrors the mark's beard block
  if (y >= 24 && y <= 31) {
    const bw = 4.6 * w + 1.4;
    if (Math.abs(x - CX) <= bw) return true;
  }
  // blazer: square shoulders tapering to a lean torso
  const shW = 16 * w + 1, bodyW = 10.5 * w + 1;
  if (y >= 33 && y <= 36) return Math.abs(x - CX) <= shW;
  if (y >= 37 && y <= 50) {
    const t = (y - 37) / 13;
    return Math.abs(x - CX) <= bodyW + (shW - bodyW) * (1 - t) * 0.35;
  }
  return false;
}

function packFrame(th) {
  const bits = new Uint8Array(GW * GH);
  for (let y = 0; y < GH; y++) {
    for (let x = 0; x < GW; x++) {
      if (fig(x, y, th)) bits[y * GW + x] = 1;
    }
  }
  const bytes = Buffer.alloc(Math.ceil(bits.length / 8));
  for (let i = 0; i < bits.length; i++) {
    if (bits[i]) bytes[i >> 3] |= 0x80 >> (i & 7);
  }
  return bytes.toString("base64");
}

const frames = Array.from({ length: N }, (_, k) => packFrame((k / N) * Math.PI * 2));

const out = `// loading-figure.ts : original procedural frames for the LoadingAnimation
// hero. Generated by scripts/generate-loading-figure.mjs (36 frames, 66x53,
// 1 bit per cell, row-major, packed MSB first). No real-person likeness;
// replace the built-in frames which were sampled from a third-party video.
export const ORIGINAL_FRAMES: string[] = ${JSON.stringify(frames, null, 1).replace(/\n\s{1,2}/g, "")};
`;

const here = dirname(fileURLToPath(import.meta.url));
const dest = join(here, "..", "components", "client", "r6", "loading-figure.ts");
writeFileSync(dest, out);

// ASCII preview of one front frame and one profile frame for a quick look.
const ascii = (th) => {
  let s = "";
  for (let y = 0; y < GH; y += 3) {
    for (let x = 0; x < GW; x += 2) s += fig(x, y, th) ? "##" : "  ";
    s += "\n";
  }
  return s;
};
console.log("front (th=0):\n" + ascii(0));
console.log("profile (th=pi/2):\n" + ascii(Math.PI / 2));
console.log(`wrote ${dest} (${frames.length} frames, ${out.length} bytes)`);